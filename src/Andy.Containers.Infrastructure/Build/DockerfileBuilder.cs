using System.Text;
using Andy.Containers.Abstractions.Images;

namespace Andy.Containers.Infrastructure.Build;

/// <summary>
/// Render a <see cref="TemplateSpec"/> into a Dockerfile that the
/// build engine can consume. Pure function over the spec — given the
/// same spec it produces the same Dockerfile bytes, so the build is
/// reproducible and the spec hash is a meaningful cache key.
/// </summary>
/// <remarks>
/// IM7 (rivoli-ai/andy-containers#261). Apple Containers consumes the
/// same Dockerfile syntax as Docker BuildKit (per the apple/container
/// reference), so one renderer covers both engines.
/// </remarks>
public static class DockerfileBuilder
{
    /// <summary>
    /// Build the Dockerfile text for the given spec. The resulting
    /// string ends with a newline so naive concatenation with
    /// downstream content stays line-oriented.
    /// </summary>
    /// <param name="spec">
    /// Spec to render. Must have <see cref="TemplateSpec.BaseImage"/>
    /// populated — by the time the build backend is called, the
    /// orchestrator has resolved any <see cref="TemplateSpec.Extends"/>
    /// chain into a concrete base image.
    /// </param>
    public static string Render(TemplateSpec spec)
    {
        ArgumentNullException.ThrowIfNull(spec);
        if (string.IsNullOrWhiteSpace(spec.BaseImage))
        {
            throw new InvalidOperationException(
                "DockerfileBuilder.Render requires TemplateSpec.BaseImage to be set. " +
                "If the spec only declares 'extends:', the orchestrator must resolve the parent chain " +
                "to a concrete base image before invoking the build backend.");
        }

        var sb = new StringBuilder();

        // Pin a syntax directive — explicit version means a newer
        // BuildKit on the host doesn't silently change behaviour.
        sb.AppendLine("# syntax=docker/dockerfile:1.7");
        sb.AppendLine($"# Generated by andy-containers DockerfileBuilder for template '{spec.Code}' (specHash {spec.SpecHash}).");
        sb.AppendLine("# Edit the source spec, not this file — regenerated on every build.");
        sb.AppendLine();

        sb.Append("FROM ");
        sb.AppendLine(spec.BaseImage);
        sb.AppendLine();

        // Shell selection — bash gives us pipefail, which we want for
        // the install commands so a piped `curl | sh` failure halts
        // the build instead of being silently masked.
        sb.AppendLine("SHELL [\"/bin/sh\", \"-eu\", \"-c\"]");
        sb.AppendLine();

        // Markers as labels. Each markers key/value list flattens to
        // one comma-joined LABEL — Docker requires LABEL values to be
        // strings. The orchestrator separately persists the structured
        // markers on BuildArtifact so this is observability-only.
        if (spec.Markers.Count > 0)
        {
            foreach (var (key, values) in spec.Markers.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            {
                var safeKey = SanitiseLabelKey(key);
                var joined = string.Join(",", values);
                sb.Append("LABEL ");
                sb.Append("ai.rivoli.andy-containers.markers.");
                sb.Append(safeKey);
                sb.Append('=');
                sb.AppendLine(QuoteShell(joined));
            }
            sb.AppendLine();
        }

        // Packages — pick the package manager from the base image.
        // The detection is best-effort; spec authors who use an
        // unusual base image can avoid `packages:` and use explicit
        // `install:` commands instead.
        if (spec.Packages.Count > 0)
        {
            var manager = DetectPackageManager(spec.BaseImage);
            sb.AppendLine($"# packages: {string.Join(", ", spec.Packages)} via {manager}");
            sb.AppendLine(RenderPackageInstall(manager, spec.Packages));
            sb.AppendLine();
        }

        // Files — COPY each entry, then chmod when a mode is set.
        // Each entry is its own COPY layer so cache invalidation
        // is granular: changing one file's content doesn't rebuild
        // every package install above it (Docker's RUN/COPY layer
        // model means Adam's law applies).
        if (spec.Files.Count > 0)
        {
            foreach (var file in spec.Files)
            {
                sb.Append("COPY ");
                sb.Append(QuoteShell(file.Source));
                sb.Append(' ');
                sb.AppendLine(QuoteShell(file.Dest));
                if (file.Mode is { } mode)
                {
                    var octal = Convert.ToString(mode, 8);
                    sb.AppendLine($"RUN chmod {octal} {QuoteShell(file.Dest)}");
                }
            }
            sb.AppendLine();
        }

        // Install commands — one RUN layer per command (clean cache
        // invalidation: changing the third install command only
        // re-runs from that command onwards).
        if (spec.Install.Count > 0)
        {
            foreach (var cmd in spec.Install)
            {
                sb.Append("RUN ");
                sb.AppendLine(cmd);
            }
            sb.AppendLine();
        }

        if (!string.IsNullOrWhiteSpace(spec.EntryPoint))
        {
            // ENTRYPOINT in JSON-array exec form — avoids the shell
            // wrapper that string-form ENTRYPOINT would interpose,
            // matching the IM4 acceptance ("single string entrypoint").
            sb.Append("ENTRYPOINT [\"");
            sb.Append(spec.EntryPoint.Replace("\\", "\\\\").Replace("\"", "\\\""));
            sb.AppendLine("\"]");
        }

        return sb.ToString();
    }

    /// <summary>
    /// Best-effort package manager detection from a base image
    /// reference. Used only when <see cref="TemplateSpec.Packages"/>
    /// is non-empty.
    /// </summary>
    public static PackageManager DetectPackageManager(string baseImage)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(baseImage);

        // The string match is a heuristic, not authoritative —
        // operator can override by using `install:` lines instead of
        // `packages:` if the heuristic miscategorises their base.
        var hint = baseImage.ToLowerInvariant();

        if (hint.Contains("alpine")) return PackageManager.Apk;
        if (hint.Contains("/redhat") || hint.Contains("ubi") ||
            hint.Contains("fedora") || hint.Contains("centos") ||
            hint.Contains("rocky") || hint.Contains("alma") ||
            hint.Contains("rhel"))
        {
            return PackageManager.Dnf;
        }
        // Default — most dev container bases are Debian / Ubuntu.
        return PackageManager.Apt;
    }

    private static string RenderPackageInstall(PackageManager manager, IReadOnlyList<string> packages)
    {
        var quoted = string.Join(' ', packages.Select(QuoteShell));
        return manager switch
        {
            PackageManager.Apt =>
                $"RUN apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends {quoted} && rm -rf /var/lib/apt/lists/*",
            PackageManager.Dnf =>
                $"RUN dnf install -y {quoted} && dnf clean all",
            PackageManager.Apk =>
                $"RUN apk add --no-cache {quoted}",
            _ => throw new InvalidOperationException($"Unsupported package manager '{manager}'."),
        };
    }

    private static string QuoteShell(string value)
    {
        // Posix-style single-quoting. Inside single quotes only the
        // single quote itself is special, so we need to terminate the
        // quoted region, emit an escaped quote, and re-open.
        if (string.IsNullOrEmpty(value))
        {
            return "''";
        }
        if (!ContainsShellMeta(value))
        {
            return value;
        }
        return "'" + value.Replace("'", "'\\''") + "'";
    }

    private static bool ContainsShellMeta(string value)
    {
        foreach (var ch in value)
        {
            if (char.IsWhiteSpace(ch)) return true;
            if (ch is '\'' or '"' or '`' or '$' or '\\' or '|' or '&' or ';' or
                      '<' or '>' or '(' or ')' or '{' or '}' or '*' or '?' or '[' or ']' or '#')
            {
                return true;
            }
        }
        return false;
    }

    private static string SanitiseLabelKey(string key)
    {
        // Docker LABEL keys must be a reverse-DNS-prefixed value;
        // we already supply the prefix. The user portion just needs
        // to stay within [A-Za-z0-9._-]; substitute everything else
        // with '-' rather than failing the build.
        var sb = new StringBuilder(key.Length);
        foreach (var ch in key)
        {
            sb.Append(char.IsLetterOrDigit(ch) || ch is '.' or '_' or '-' ? ch : '-');
        }
        return sb.ToString();
    }
}

public enum PackageManager
{
    Apt,
    Dnf,
    Apk,
}
